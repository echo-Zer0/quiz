#!/usr/bin/env bash

# ==============================================================================
# ⚡ CYBER-QUIZ PLATFORM: Universal Startup Engine
# ==============================================================================
# Handles Python venv creation, Pip install, NPM install, .env file creation,
# and concurrent execution of Backend (FastAPI) & Frontend (Next.js) with cleanup.
# ==============================================================================

set -eo pipefail

# Style & Colors
BOLD='\033[1m'
CYAN='\033[0;36m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
NC='\033[0m' # No Color

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BACKEND_DIR="${ROOT_DIR}/backend"
FRONTEND_DIR="${ROOT_DIR}/frontend"

echo -e "${CYAN}${BOLD}"
cat << "EOF"
  ██████╗██╗   ██╗██████╗ ███████╗██████╗        ██████╗ ██╗   ██╗██╗███████╗
 ██╔════╝╚██╗ ██╔╝██╔══██╗██╔════╝██╔══██╗      ██╔═══██╗██║   ██║██║╚══███╔╝
 ██║      ╚████╔╝ ██████╔╝█████╗  ██████╔╝█████╗██║   ██║██║   ██║██║  ███╔╝ 
 ██║       ╚██╔╝  ██╔══██╗██╔══╝  ██╔══██╗╚════╝██║▄▄ ██║██║   ██║██║ ███╔╝  
 ╚██████╗   ██║   ██████╔╝███████╗██║  ██║      ╚██████╔╝╚██████╔╝██║███████╗
  ╚═════╝   ╚═╝   ╚═════╝ ╚══════╝╚═╝  ╚═╝       ╚══▀▀═╝  ╚═════╝ ╚═╝╚══════╝
EOF
echo -e "${NC}"
echo -e "${BOLD}[*] Initializing Cyber-Quiz Platform Environment...${NC}\n"

# ------------------------------------------------------------------------------
# 1. Dependency & Prerequisite Verification
# ------------------------------------------------------------------------------
check_command() {
    if ! command -v "$1" &> /dev/null; then
        echo -e "${RED}[✗] Required tool '$1' is not installed or not in PATH.${NC}"
        exit 1
    fi
}

echo -e "${BOLD}[1/4] Verifying System Prerequisites...${NC}"
check_command python3
check_command node
check_command npm

# Verify project structure
if [[ ! -d "$BACKEND_DIR" || ! -d "$FRONTEND_DIR" ]]; then
    echo -e "${RED}[✗] Missing 'backend' or 'frontend' directory. Execute this script from the project root.${NC}"
    exit 1
fi
echo -e "${GREEN}[✓] System tools and folder structure verified.${NC}\n"

# ------------------------------------------------------------------------------
# 2. Backend Provisioning (FastAPI)
# ------------------------------------------------------------------------------
echo -e "${BOLD}[2/4] Provisioning Backend Services...${NC}"
cd "$BACKEND_DIR"

# Python virtual environment
if [[ ! -d ".venv" ]]; then
    echo -e "${YELLOW}[i] Creating Python virtual environment (.venv)...${NC}"
    python3 -m venv .venv
fi

# Activate venv
# shellcheck source=/dev/null
source .venv/bin/activate

# Install / update requirements
echo -e "${YELLOW}[i] Checking backend dependencies...${NC}"
pip install --upgrade pip --quiet
pip install -r requirements.txt --quiet

# Scaffolding default .env for backend if not present
if [[ ! -f ".env" ]]; then
    echo -e "${YELLOW}[i] No .env found. Generating default local-mode backend configuration...${NC}"
    RANDOM_JWT=$(python3 -c "import secrets; print(secrets.token_hex(32))")
    cat << EOF > .env
# Auto-generated by run.sh (Local SQLite fallback mode)
HOST=0.0.0.0
PORT=8000
JWT_SECRET=${RANDOM_JWT}
FRONTEND_URL=http://localhost:3000
# SUPABASE_URL=https://your-project.supabase.co
# SUPABASE_KEY=your-supabase-service-role-key
EOF
    echo -e "${GREEN}[✓] Created backend/.env (Fallback SQLite Engine Enabled)${NC}"
fi
echo -e "${GREEN}[✓] Backend service ready.${NC}\n"

# ------------------------------------------------------------------------------
# 3. Frontend Provisioning (Next.js)
# ------------------------------------------------------------------------------
echo -e "${BOLD}[3/4] Provisioning Frontend Client...${NC}"
cd "$FRONTEND_DIR"

if [[ ! -d "node_modules" ]]; then
    echo -e "${YELLOW}[i] Installing frontend node modules (npm install)...${NC}"
    npm install
fi

# Scaffolding default .env.local for frontend if not present
if [[ ! -f ".env.local" ]]; then
    echo -e "${YELLOW}[i] No .env.local found. Scaffolding default frontend environment...${NC}"
    cat << EOF > .env.local
NEXT_PUBLIC_API_URL=http://localhost:8000
NEXT_PUBLIC_WS_URL=ws://localhost:8000
EOF
    echo -e "${GREEN}[✓] Created frontend/.env.local${NC}"
fi
echo -e "${GREEN}[✓] Frontend client ready.${NC}\n"

# ------------------------------------------------------------------------------
# 4. Process Supervisor & Cleanup Traps
# ------------------------------------------------------------------------------
BACKEND_PID=""
FRONTEND_PID=""

cleanup() {
    echo -e "\n${YELLOW}[!] Interruption signal caught. Terminating active services...${NC}"
    if [[ -n "$BACKEND_PID" ]] && kill -0 "$BACKEND_PID" 2>/dev/null; then
        kill "$BACKEND_PID" 2>/dev/null || true
    fi
    if [[ -n "$FRONTEND_PID" ]] && kill -0 "$FRONTEND_PID" 2>/dev/null; then
        kill "$FRONTEND_PID" 2>/dev/null || true
    fi
    wait 2>/dev/null || true
    echo -e "${GREEN}[✓] All platform processes stopped safely.${NC}"
    exit 0
}

trap cleanup SIGINT SIGTERM EXIT

# ------------------------------------------------------------------------------
# 5. Booting Concurrent Services
# ------------------------------------------------------------------------------
echo -e "${BOLD}[4/4] Launching Real-Time Services...${NC}"

# Boot Backend
cd "$BACKEND_DIR"
source .venv/bin/activate
uvicorn app.main:app --host 0.0.0.0 --port 8000 --reload &
BACKEND_PID=$!
echo -e "${GREEN}[▶] Backend live on:${NC} http://localhost:8000 (Swagger: http://localhost:8000/docs)"

# Boot Frontend
cd "$FRONTEND_DIR"
npm run dev &
FRONTEND_PID=$!
echo -e "${GREEN}[▶] Frontend live on:${NC} http://localhost:3000"

echo -e "\n${CYAN}${BOLD}[★] CYBER-QUIZ ARENA IS LIVE! Press Ctrl+C at any time to shut down.${NC}\n"

# Maintain foreground thread and wait on background processes
wait "$BACKEND_PID" "$FRONTEND_PID"
